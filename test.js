// Example usage of RzipJS class
function main() {
  console.log("Starting RzipJS test...");

  const start_hash = crypto
    .createHash("md5")
    .update(Buffer.from(rzipData))
    .digest("hex");
  console.log("MD5 of input RZIP data:", start_hash);

  const rzip = new RzipJS(rzipData);
  console.log("Decompressing RZIP data...");
  try {
    const expected_output_length = Number(rzip.header.inflated_size);
    console.log("Expected decompressed data length:", expected_output_length);
    const decompressedData = rzip.rzip_inflate();
    console.log(
      "Decompression complete. Decompressed data length:",
      decompressedData.length
    );
    if (decompressedData.length !== expected_output_length) {
      console.error(
        "Error: Decompressed data length does not match expected length."
      );
      return;
    } else {
      console.log("Decompressed data length matches expected length.");
    }
  } catch (e) {
    console.error("Decompression failed:", e.message);
    return;
  }

  try {
    console.log("Recompressing data back to RZIP format...");
    const recompressedData = rzip.rzip_deflate();
    console.log(
      "Recompression complete. Recompressed data length:",
      recompressedData.length
    );

    const end_hash = crypto
      .createHash("md5")
      .update(Buffer.from(recompressedData))
      .digest("hex");
    console.log("MD5 of recompressed RZIP data:", end_hash);

    if (start_hash === end_hash) {
      console.log("Success: Recompressed data matches original RZIP data.");
    } else {
      console.error("Error: Recompressed data does not match original.");
    }
  } catch (e) {
    console.error("Recompression failed:", e.message);
    return;
  }
}

function array_equal(a, b) {
  if (a.length !== b.length) {
    return false;
  }
  for (let i = 0; i < a.length; i++) {
    if (a[i] !== b[i]) return false;
  }
  return true;
}

